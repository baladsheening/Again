/*
 * ─────────────────────────────────────────────────────────────────────────────
 *  The service worker — earned push, 11 September
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * **The whole of it, and it does one thing.** It shows a notification when one
 * arrives and opens the app when one is tapped. It does not cache, it does not
 * intercept a fetch, and it must not learn to: an offline shell is a separate
 * decision with its own failure modes, and a worker that caches will one day
 * serve a stale build to somebody who cannot work out why.
 *
 * ⚠ **PLAIN JS IN `public/`, WITH NO BUILD STEP.** `next build` does not
 * compile this file, so there is no TypeScript, no import, and no bundler here.
 * A syntax error is a worker that fails to register and nothing on screen says
 * so — which is why this is kept as small as it can be.
 *
 * ⚠ **`proxy.ts`'s matcher ALREADY excludes `sw.js`** — it has since before
 * this file existed — and the CSP already carries `worker-src 'self'`. Neither
 * had to be touched. **Do not put this file behind the proxy**: a service worker
 * served with a nonce CSP and a rewritten path is a worker the browser refuses
 * at a scope it cannot explain.
 *
 * ⚠ **Scope is the root, because the file is at the root.** A worker's default
 * scope is its own directory, so `/sw.js` controls `/` and everything under it.
 * Moving it into a subdirectory silently narrows that and needs a
 * `Service-Worker-Allowed` header to widen again.
 */

/*
  ⚠ **`self.skipWaiting()` and `clients.claim()` together, deliberately.**
  Without them a replaced worker waits for every tab to close, so somebody who
  never quits the installed app keeps the old one for weeks — and the thing that
  changed was how a notification is drawn. There is no cache to invalidate and
  no in-flight state to lose, which is exactly the condition that makes taking
  over immediately safe here and unsafe in a worker that caches.
*/
self.addEventListener('install', () => self.skipWaiting())
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()))

self.addEventListener('push', (event) => {
  /*
    ⚠ **A push with no data is ignored rather than drawn.** Some user agents
    deliver an empty push to wake a worker; drawing "New notification" for one
    would be the app inventing an event nobody caused.
  */
  if (!event.data) return

  let payload
  try {
    payload = event.data.json()
  } catch {
    return
  }

  const title = payload.title
  if (!title) return

  event.waitUntil(
    self.registration.showNotification(title, {
      body: payload.body,
      /*
        ⚠ **The app's own icon, and no badge.** A badge is the monochrome glyph
        Android draws in the status bar; there is no such asset and a missing one
        renders as a grey square. `apple-icon` is generated by the app.
      */
      icon: '/apple-icon',
      /*
        ⚠⚠ **`tag` COLLAPSES A BURST INTO ONE, AND THAT IS NOT COSMETIC.**
        `runOverlapForNewMutual` is deliberately uncapped — two people with forty
        things in common produce forty matches at the moment they connect — and
        forty separate notifications is the flood this product exists not to be.
        Tagging by kind means the newest replaces the last.
        ⚠ **`renotify` is deliberately absent**: a replacement must not buzz
        again, or the collapse buys nothing.
      */
      tag: payload.tag || 'juce',
      data: { url: payload.url || '/record' },
    }),
  )
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()

  /*
    ⚠ **Focus an open window before opening a new one.** Somebody with the
    installed app already running should be taken to it, not given a second
    copy — and on iOS a second window is a second scroll position in a product
    whose whole promise is that Return lands where you left it.
  */
  const url = (event.notification.data && event.notification.data.url) || '/record'
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windows) => {
      for (const client of windows) {
        if ('focus' in client) {
          if ('navigate' in client) client.navigate(url)
          return client.focus()
        }
      }
      return self.clients.openWindow(url)
    }),
  )
})
